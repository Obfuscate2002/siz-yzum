const normalize = (value: string) =>
    value.trim().replace(/\s+/g, " ").toLowerCase();

export const ImportContractPositions = ({
                                            pb,
                                        }: ImportContractPositionsProps) => {
    const [loading, setLoading] = useState(false);

    const handleImport = async () => {
        setLoading(true);

        let created = 0;
        let skipped = 0;
        const errors: string[] = [];

        try {
            // Загружаем подразделения
            const divisions = await pb.collection("divisions").getFullList({
                fields: "id,name",
            });

            const divisionMap = new Map(
                divisions.map((item) => [normalize(item.name || ""), item])
            );

            // Загружаем существующие должности по ТД
            const existing = await pb.collection("contract_positions").getFullList({
                fields: "id,name,division,exception_employee",
            });

            // Ключ: должность + подразделение
            const existingKeys = new Set(
                existing.map((item) =>
                    `${normalize(item.name || "")}|${item.division || ""}`
                )
            );

            for (const [name, divisionName, exceptionEmployee] of contractPositionsData) {
                const division = divisionMap.get(normalize(divisionName));

                if (!division) {
                    errors.push(`Не найдено подразделение: ${divisionName}`);
                    continue;
                }

                const key = `${normalize(name)}|${division.id}`;

                if (existingKeys.has(key)) {
                    skipped++;
                    continue;
                }

                try {
                    await pb.collection("contract_positions").create({
                        name,
                        division: division.id,
                        exception_employee: exceptionEmployee,
                    });

                    existingKeys.add(key);
                    created++;
                } catch (error) {
                    console.error(`Ошибка создания должности "${name}":`, error);
                    errors.push(`${name} — ${divisionName}`);
                }
            }

            Modal.info({
                title: "Результат импорта должностей по ТД",
                content: (
                    <div>
                        <p>Всего записей в исходном файле: <b>{contractPositionsData.length}</b></p>
                        <p>Создано новых записей: <b>{created}</b></p>
                        <p>Пропущено (уже существуют): <b>{skipped}</b></p>
                        <p>Ошибок: <b>{errors.length}</b></p>

                        {errors.length > 0 && (
                            <>
                                <p><b>Список ошибок:</b></p>
                                <ul>
                                    {errors.map((error, index) => (
                                        <li key={index}>{error}</li>
                                    ))}
                                </ul>
                            </>
                        )}
                    </div>
                ),
            });

            if (errors.length === 0) {
                message.success("Импорт должностей по ТД завершён!");
            } else {
                message.warning("Импорт завершён с ошибками. Проверь результат.");
            }
        } catch (error) {
            console.error("Ошибка импорта:", error);
            message.error("Не удалось выполнить импорт");
        } finally {
            setLoading(false);
        }
    };

    return (
        <Button
            type="primary"
            icon={<DatabaseOutlined />}
            loading={loading}
            onClick={handleImport}
        >
            Импортировать должности по ТД
        </Button>
    );
};
